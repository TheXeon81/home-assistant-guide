# Come installare Home Assistant con Docker su Windows
# Sezione / Section: Passo 1 — Attiva WSL2
# Guida completa (in italiano) / Full guide (in Italian):
# https://www.lucianoblancato.it/home-assistant/installare-home-assistant-docker-windows.html

# Abilita WSL2 e installa una distribuzione Linux di base (serve solo come motore per Docker)
wsl --install

# Controlla la versione: deve rispondere con un numero, non con un errore
wsl --version
